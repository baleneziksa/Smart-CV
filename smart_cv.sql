CREATE DATABASE IF NOT EXISTS smart_cv CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE smart_cv;

CREATE TABLE IF NOT EXISTS users (
  user_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS resumes (
  resume_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL,
  title VARCHAR(150) NOT NULL DEFAULT 'سيرتي الذاتية',
  full_name VARCHAR(150) NOT NULL,
  job_title VARCHAR(150) DEFAULT NULL,
  email VARCHAR(190) DEFAULT NULL,
  phone VARCHAR(30) DEFAULT NULL,
  city VARCHAR(120) DEFAULT NULL,
  linkedin_url VARCHAR(500) DEFAULT NULL,
  summary TEXT DEFAULT NULL,
  template_name ENUM('classic','modern','professional') NOT NULL DEFAULT 'classic',
  ats_score TINYINT UNSIGNED DEFAULT NULL,
  shareable_token VARCHAR(64) UNIQUE DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_resumes_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS education (
  education_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  resume_id INT UNSIGNED NOT NULL,
  degree VARCHAR(150) DEFAULT NULL,
  major VARCHAR(150) DEFAULT NULL,
  school VARCHAR(200) DEFAULT NULL,
  graduation_year VARCHAR(30) DEFAULT NULL,
  CONSTRAINT fk_education_resume FOREIGN KEY (resume_id) REFERENCES resumes(resume_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS experiences (
  experience_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  resume_id INT UNSIGNED NOT NULL,
  position VARCHAR(150) DEFAULT NULL,
  company VARCHAR(200) DEFAULT NULL,
  start_date VARCHAR(30) DEFAULT NULL,
  end_date VARCHAR(30) DEFAULT NULL,
  description TEXT DEFAULT NULL,
  CONSTRAINT fk_experiences_resume FOREIGN KEY (resume_id) REFERENCES resumes(resume_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS skills (
  skill_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  resume_id INT UNSIGNED NOT NULL,
  skill_name VARCHAR(150) NOT NULL,
  CONSTRAINT fk_skills_resume FOREIGN KEY (resume_id) REFERENCES resumes(resume_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS languages (
  language_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  resume_id INT UNSIGNED NOT NULL,
  language_name VARCHAR(100) NOT NULL,
  proficiency_level VARCHAR(50) DEFAULT NULL,
  CONSTRAINT fk_languages_resume FOREIGN KEY (resume_id) REFERENCES resumes(resume_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS certifications (
  certification_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  resume_id INT UNSIGNED NOT NULL,
  title VARCHAR(200) NOT NULL,
  issuer VARCHAR(200) DEFAULT NULL,
  issue_date CHAR(7) DEFAULT NULL,
  certificate_url VARCHAR(500) DEFAULT NULL,
  CONSTRAINT fk_certifications_resume FOREIGN KEY (resume_id) REFERENCES resumes(resume_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS projects (
  project_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  resume_id INT UNSIGNED NOT NULL,
  title VARCHAR(200) NOT NULL,
  project_url VARCHAR(500) DEFAULT NULL,
  description TEXT DEFAULT NULL,
  CONSTRAINT fk_projects_resume FOREIGN KEY (resume_id) REFERENCES resumes(resume_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS volunteering (
  volunteering_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  resume_id INT UNSIGNED NOT NULL,
  role_title VARCHAR(150) DEFAULT NULL,
  organization VARCHAR(200) DEFAULT NULL,
  start_date VARCHAR(30) DEFAULT NULL,
  end_date VARCHAR(30) DEFAULT NULL,
  description TEXT DEFAULT NULL,
  CONSTRAINT fk_volunteering_resume FOREIGN KEY (resume_id) REFERENCES resumes(resume_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS resume_references (
  reference_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  resume_id INT UNSIGNED NOT NULL,
  full_name VARCHAR(150) DEFAULT NULL,
  position VARCHAR(150) DEFAULT NULL,
  organization VARCHAR(200) DEFAULT NULL,
  contact VARCHAR(200) DEFAULT NULL,
  CONSTRAINT fk_references_resume FOREIGN KEY (resume_id) REFERENCES resumes(resume_id) ON DELETE CASCADE
) ENGINE=InnoDB;
